using System.Collections.Generic;
using System.Linq;
using System.Net;
using System.Text.Json.Nodes;
using System.Threading.Tasks;

public class DesignInfo
{
    public string FileName;
    public string FileType;
    public string ItemId;
    public string ItemType; // e.g., "items:autodesk.bim360:File", or "items:autodesk.bim360:C4RModel" for cloud workshared models
    public string FolderId;
    public string StorageUrn;
    public string Region;
}

public class CreatedVersion
{
    public string ItemId;
    public string VersionId;
    public int VersionNumber;
}

public class DerivativeView
{
    public string Name;
    public string Role;
    // Views generated by the extraction (e.g., "New Construction"), rather than views of the Revit file
    public bool IsMasterView;
}

public class Manifest
{
    public string Status;
    public string Progress;
}

// Data Management (ACC files) and Model Derivative (processing of the uploaded files) operations
public partial class APS
{
    private const string JsonApiContentType = "application/vnd.api+json";
    private static readonly JsonObject JsonApi = new() { ["version"] = "1.0" };

    public async Task<DesignInfo> GetDesignInfo(string hubId, string projectId, string versionId, Tokens tokens)
    {
        var version = await GetAsync($"/data/v1/projects/{projectId}/versions/{Encode(versionId)}", tokens.InternalToken);
        var itemId = (string)version["data"]["relationships"]["item"]["data"]["id"];
        var item = await GetAsync($"/data/v1/projects/{projectId}/items/{Encode(itemId)}", tokens.InternalToken);
        var hub = await GetAsync($"/project/v1/hubs/{hubId}", tokens.InternalToken);
        var attributes = version["data"]["attributes"];
        return new DesignInfo
        {
            FileName = (string)attributes["name"],
            FileType = (string)attributes["fileType"],
            ItemId = itemId,
            ItemType = (string)item["data"]["attributes"]["extension"]?["type"],
            FolderId = (string)item["data"]["relationships"]["parent"]["data"]["id"],
            // Cloud workshared models do not have a storage object that could be downloaded
            StorageUrn = (string)version["data"]["relationships"]["storage"]?["data"]?["id"],
            Region = (string)hub["data"]["attributes"]["region"] ?? "US"
        };
    }

    // Reserves a storage object for a new file (or file version) in the given folder
    public async Task<string> CreateStorage(string projectId, string folderId, string fileName, Tokens tokens)
    {
        var body = new JsonObject
        {
            ["jsonapi"] = JsonApi.DeepClone(),
            ["data"] = new JsonObject
            {
                ["type"] = "objects",
                ["attributes"] = new JsonObject { ["name"] = fileName },
                ["relationships"] = new JsonObject
                {
                    ["target"] = new JsonObject { ["data"] = new JsonObject { ["type"] = "folders", ["id"] = folderId } }
                }
            }
        };
        var result = await PostAsync($"/data/v1/projects/{projectId}/storage", tokens.InternalToken, body, JsonApiContentType);
        return (string)result["data"]["id"];
    }

    public async Task<string> FindItemInFolder(string projectId, string folderId, string fileName, Tokens tokens)
    {
        string url = $"/data/v1/projects/{projectId}/folders/{Encode(folderId)}/contents?filter[type]=items";
        while (url != null)
        {
            var page = await GetAsync(url, tokens.InternalToken);
            var match = page["data"].AsArray().FirstOrDefault(entry => (string)entry["attributes"]["displayName"] == fileName);
            if (match != null)
            {
                return (string)match["id"];
            }
            url = (string)page["links"]?["next"]?["href"];
        }
        return null;
    }

    // Creates a new item, or a new version of an existing item with the same name, from an uploaded storage object
    public async Task<CreatedVersion> CreateFileVersion(string projectId, string folderId, string fileName, string storageUrn, Tokens tokens)
    {
        var storage = new JsonObject { ["data"] = new JsonObject { ["type"] = "objects", ["id"] = storageUrn } };
        var versionAttributes = new JsonObject
        {
            ["name"] = fileName,
            ["extension"] = new JsonObject { ["type"] = "versions:autodesk.bim360:File", ["version"] = "1.0" }
        };
        var existingItemId = await FindItemInFolder(projectId, folderId, fileName, tokens);
        JsonNode version;
        string itemId;
        if (existingItemId == null)
        {
            var body = new JsonObject
            {
                ["jsonapi"] = JsonApi.DeepClone(),
                ["data"] = new JsonObject
                {
                    ["type"] = "items",
                    ["attributes"] = new JsonObject
                    {
                        ["displayName"] = fileName,
                        ["extension"] = new JsonObject { ["type"] = "items:autodesk.bim360:File", ["version"] = "1.0" }
                    },
                    ["relationships"] = new JsonObject
                    {
                        ["tip"] = new JsonObject { ["data"] = new JsonObject { ["type"] = "versions", ["id"] = "1" } },
                        ["parent"] = new JsonObject { ["data"] = new JsonObject { ["type"] = "folders", ["id"] = folderId } }
                    }
                },
                ["included"] = new JsonArray
                {
                    new JsonObject
                    {
                        ["type"] = "versions",
                        ["id"] = "1",
                        ["attributes"] = versionAttributes,
                        ["relationships"] = new JsonObject { ["storage"] = storage }
                    }
                }
            };
            var result = await PostAsync($"/data/v1/projects/{projectId}/items", tokens.InternalToken, body, JsonApiContentType);
            itemId = (string)result["data"]["id"];
            version = result["included"][0];
        }
        else
        {
            var body = new JsonObject
            {
                ["jsonapi"] = JsonApi.DeepClone(),
                ["data"] = new JsonObject
                {
                    ["type"] = "versions",
                    ["attributes"] = versionAttributes,
                    ["relationships"] = new JsonObject
                    {
                        ["item"] = new JsonObject { ["data"] = new JsonObject { ["type"] = "items", ["id"] = existingItemId } },
                        ["storage"] = storage
                    }
                }
            };
            var result = await PostAsync($"/data/v1/projects/{projectId}/versions", tokens.InternalToken, body, JsonApiContentType);
            itemId = existingItemId;
            version = result["data"];
        }
        return new CreatedVersion
        {
            ItemId = itemId,
            VersionId = (string)version["id"],
            VersionNumber = (int?)version["attributes"]?["versionNumber"] ?? 1
        };
    }

    // ACC processes uploaded files automatically; the derivative URN becomes available on the version once it does
    public async Task<string> GetDerivativeUrn(string projectId, string versionId, Tokens tokens)
    {
        var version = await GetAsync($"/data/v1/projects/{projectId}/versions/{Encode(versionId)}", tokens.InternalToken);
        return (string)version["data"]["relationships"]["derivatives"]?["data"]?["id"];
    }

    private const string ModelDerivativeUrl = "/modelderivative/v2/designdata";

    // Hubs outside the US (e.g., "EMEA", "AUS", "DEU") keep their derivatives in their own region
    private static Dictionary<string, string> RegionHeaders(string region)
        => string.IsNullOrEmpty(region) || region == "US" ? null : new Dictionary<string, string> { ["region"] = region };

    public async Task<Manifest> GetManifest(string urn, string region, Tokens tokens)
    {
        try
        {
            var manifest = await GetAsync($"{ModelDerivativeUrl}/{urn}/manifest", tokens.InternalToken, RegionHeaders(region));
            return new Manifest { Status = (string)manifest["status"], Progress = (string)manifest["progress"] };
        }
        catch (APSException ex) when (ex.StatusCode == HttpStatusCode.NotFound)
        {
            return null;
        }
    }

    // Revit version the design was saved with, as recorded by the Revit extraction in the manifest (e.g., "2023")
    public async Task<int?> GetRevitVersion(string urn, string region, Tokens tokens)
    {
        var manifest = await GetAsync($"{ModelDerivativeUrl}/{urn}/manifest", tokens.InternalToken, RegionHeaders(region));
        return FindProperty(manifest, "RVTVersion") is string value && int.TryParse(value, out var version) ? version : null;
    }

    private static string FindProperty(JsonNode node, string name)
    {
        switch (node)
        {
            case JsonObject obj:
                foreach (var (key, value) in obj)
                {
                    if (key == name && value is JsonValue)
                    {
                        return value.ToString();
                    }
                    if (FindProperty(value, name) is string found)
                    {
                        return found;
                    }
                }
                break;
            case JsonArray array:
                foreach (var item in array)
                {
                    if (FindProperty(item, name) is string found)
                    {
                        return found;
                    }
                }
                break;
        }
        return null;
    }

    public async Task<List<DerivativeView>> GetViews(string urn, string region, Tokens tokens)
    {
        var metadata = await GetAsync($"{ModelDerivativeUrl}/{urn}/metadata", tokens.InternalToken, RegionHeaders(region));
        return metadata["data"]["metadata"].AsArray().Select(view => new DerivativeView
        {
            Name = (string)view["name"],
            Role = (string)view["role"],
            IsMasterView = (bool?)view["isMasterView"] ?? false
        }).ToList();
    }
}
